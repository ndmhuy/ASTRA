"""Generate new semantic resources without changing the legacy Worker fingerprint."""

import argparse
import json
from hashlib import sha256
from pathlib import Path

from exam_baseline.agent.contracts import Turn
from exam_baseline.agent.native import SYSTEM, gemini_request
from exam_baseline.agent.semantics import CATALOG, SemanticTurn, semantic_schema

ROOT = Path(__file__).resolve().parents[1]


def export():
    resources = {
        "system": SYSTEM,
        "catalog": CATALOG,
        "turnSchema": SemanticTurn.model_json_schema(),
        "canonicalSchema": semantic_schema(),
        "providerSchema": semantic_schema(compact=True),
    }
    resources["contractHash"] = sha256(json.dumps(resources, sort_keys=True).encode()).hexdigest()
    return resources


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    resources = export()
    targets = {
        ROOT / "workers/astra-ai-proxy/src/semantic.generated.json": resources,
        ROOT / "src/exam_baseline/resources/agent/semantic-contract.json": {
            "schemaVersion": CATALOG["schemaVersion"],
            "contractHash": resources["contractHash"],
        },
        ROOT / "eval/agent-semantic/native-wire.fixture.json": {
            "provenance": "Generated by the native Gemini builder used by direct diagnostics.",
            "request": gemini_request(
                Turn(
                    schemaVersion="astra-intent-v1",
                    clientMessageId="a" * 36,
                    workspaceId="b" * 36,
                    message="Natural fixture",
                    context={"screen": "start", "setup": False},
                ),
                512,
            ),
        },
    }
    for path, value in targets.items():
        content = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
        if args.check:
            if not path.is_file() or path.read_text("utf-8") != content:
                raise SystemExit(
                    "Semantic contract is stale; run scripts/export_semantic_contract.py"
                )
        else:
            path.write_text(content, encoding="utf-8")
